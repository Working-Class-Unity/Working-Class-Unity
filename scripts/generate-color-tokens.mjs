import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { BackgroundColor, Color, Theme } from '@adobe/leonardo-contrast-colors'

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url))

export const GENERATED_FILE = resolve(repositoryRoot, 'app/assets/css/color-primitives.generated.css')

export const BRAND_COLORS = Object.freeze({
  navy: '#04334f',
  red: '#ef2525',
  orange: '#ff9f48',
  canvas: '#f7f9fc',
  ink: '#232323'
})

export const CONTRAST_STEPS = Object.freeze({
  100: 1.1,
  200: 1.5,
  500: 3,
  700: 4.5,
  800: 7
})

// Small headroom prevents HEX rounding from dropping a generated value below its named minimum.
const LEONARDO_RATIOS = Object.freeze({
  100: 1.12,
  200: 1.52,
  500: 3.1,
  700: 4.6,
  800: 7.1
})

export const SCALE_SEEDS = Object.freeze({
  navy: BRAND_COLORS.navy,
  red: BRAND_COLORS.red,
  orange: BRAND_COLORS.orange,
  ink: BRAND_COLORS.ink,
  success: '#1e6b52'
})

function createContrastTheme() {
  const ratiosFor = (name) =>
    Object.fromEntries(Object.entries(LEONARDO_RATIOS).map(([step, ratio]) => [`${name}-${step}`, ratio]))

  const background = new BackgroundColor({
    name: 'canvas',
    colorKeys: [BRAND_COLORS.canvas],
    colorSpace: 'OKLCH',
    ratios: { canvas: 1 }
  })

  const colors = Object.entries(SCALE_SEEDS).map(
    ([name, seed]) =>
      new Color({
        name,
        colorKeys: [seed],
        colorSpace: 'OKLCH',
        ratios: ratiosFor(name)
      })
  )

  return new Theme({
    colors,
    backgroundColor: background,
    lightness: 98,
    output: 'HEX',
    formula: 'wcag2'
  })
}

function normalizeHex(value) {
  const hex = value.toLowerCase()
  const channels = hex.match(/^#([\da-f])\1([\da-f])\2([\da-f])\3$/)
  return channels ? `#${channels[1]}${channels[2]}${channels[3]}` : hex
}

export function buildColorPrimitives() {
  const pairs = createContrastTheme().contrastColorPairs

  if (pairs.background.toLowerCase() !== BRAND_COLORS.canvas) {
    throw new Error(`Leonardo canvas drifted: expected ${BRAND_COLORS.canvas}, received ${pairs.background}`)
  }

  const lines = [
    '/* Generated by scripts/generate-color-tokens.mjs. Do not edit manually. */',
    ':root {',
    '  /* Exact brand anchors. */',
    '  --primitive-white: #fff;',
    `  --primitive-brand-navy: ${BRAND_COLORS.navy};`,
    `  --primitive-brand-red: ${BRAND_COLORS.red};`,
    `  --primitive-brand-orange: ${BRAND_COLORS.orange};`,
    `  --primitive-brand-canvas: ${BRAND_COLORS.canvas};`,
    `  --primitive-brand-ink: ${BRAND_COLORS.ink};`,
    `  --primitive-functional-success: ${SCALE_SEEDS.success};`,
    '',
    '  /* Leonardo WCAG 2 contrast scales against the light canvas. */'
  ]

  for (const family of Object.keys(SCALE_SEEDS)) {
    for (const step of Object.keys(CONTRAST_STEPS)) {
      const name = `${family}-${step}`
      const value = pairs[name]

      if (!value) {
        throw new Error(`Leonardo did not generate ${name}`)
      }

      lines.push(`  --primitive-${name}: ${normalizeHex(value)};`)
    }
  }

  lines.push('}', '')
  return lines.join('\n')
}

function main() {
  const args = process.argv.slice(2)
  const check = args.length === 1 && args[0] === '--check'

  if (args.length > 0 && !check) {
    console.error('Usage: node scripts/generate-color-tokens.mjs [--check]')
    process.exitCode = 64
    return
  }

  const generated = buildColorPrimitives()

  if (check) {
    const current = existsSync(GENERATED_FILE) ? readFileSync(GENERATED_FILE, 'utf8') : ''

    if (current !== generated) {
      console.error('Generated color tokens are stale. Run pnpm tokens:generate.')
      process.exitCode = 1
      return
    }

    console.log('Generated color tokens are current.')
    return
  }

  writeFileSync(GENERATED_FILE, generated)
  console.log('Generated app/assets/css/color-primitives.generated.css.')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
}
